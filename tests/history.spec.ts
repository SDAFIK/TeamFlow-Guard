import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const fixture = JSON.parse(readFileSync('.local/hosted-demo.json', 'utf8'));
test('browse persisted history without duplicates and reject invalid cursors', async ({ page }) => {
  test.setTimeout(120_000);
  if (process.env.TEAMFLOW_VERCEL_SHARE_FILE) await page.goto(JSON.parse(readFileSync(process.env.TEAMFLOW_VERCEL_SHARE_FILE, 'utf8')).url);
  await page.goto('/audit');
  await page.getByLabel('Email address').fill('asha@teamflow.demo');
  await page.getByLabel('Password', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByLabel('Project', { exact: true })).toBeVisible({ timeout: 60000 });
  const projects = await (await page.request.get('/api/projects')).json();
  const workspace = projects.find((p: { name: string }) => p.name === 'Checkout Launch');
  expect(workspace).toBeTruthy();
  await page.getByLabel('Project', { exact: true }).selectOption(workspace.id);
  const base = `/api/projects/${workspace.id}/audit`;
  const integrations = await (await page.request.get(`/api/projects/${workspace.id}/integrations`)).json();
  expect(integrations.github_configured).toBe(true);
  const risks = await (await page.request.get(`/api/projects/${workspace.id}/risks`)).json();
  expect(risks.some((risk: { evidence: { origin: string; payload: { source_url?: string } } }) => risk.evidence.origin === 'github' && risk.evidence.payload.source_url?.startsWith('https://github.com/SDAFIK/TeamFlow-Guard/actions/runs/'))).toBe(true);
  const firstResponse = await page.request.get(`${base}?limit=1`);
  expect(firstResponse.status()).toBe(200);
  const first = await firstResponse.json();
  expect(first.items).toHaveLength(1); expect(first.next_cursor).toBeTruthy();
  const second = await (await page.request.get(`${base}?limit=1&cursor=${first.next_cursor}`)).json();
  expect(second.items).toHaveLength(1); expect(second.items[0].id).not.toBe(first.items[0].id);
  expect((await page.request.get(`${base}?limit=0`)).status()).toBe(422);
  expect((await page.request.get(`${base}?limit=25&cursor=invalid`)).status()).toBe(422);
  expect((await page.request.get('/api/projects/00000000-0000-4000-8000-000000000000/audit?limit=25')).status()).toBe(404);
  await page.goto('/audit');
  const history = page.getByRole('region', { name: 'Audit history' });
  await expect(history.getByRole('button', { name: 'Refresh history' })).toBeEnabled({ timeout: 30000 });
  const initial = await history.locator('details').count();
  const older = history.getByRole('button', { name: 'Load older events' });
  if (await older.count()) { await older.click(); await expect.poll(() => history.locator('details').count()).toBeGreaterThan(initial); }
  await history.locator('summary').first().click();
  await expect(history.locator('.audit-detail').first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `evidence/history-${test.info().project.name}.png`, fullPage: true });
});
