import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const fixture = JSON.parse(readFileSync(".local/hosted-demo.json", "utf8"));
test("Supabase judge flow, routes, rejection, approval, persistence and viewer denial", async ({ page }, info) => {
  test.setTimeout(process.env.TEAMFLOW_VERCEL_SHARE_FILE ? 360_000 : 180_000);
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  if (process.env.TEAMFLOW_VERCEL_SHARE_FILE) {
    const share = JSON.parse(readFileSync(process.env.TEAMFLOW_VERCEL_SHARE_FILE, 'utf8'));
    await page.goto(share.url);
  }
  await page.goto("/overview");
  await page.getByLabel("Email address").fill("asha@teamflow.demo");
  await page.getByLabel("Password", { exact: true }).fill(fixture.password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Delivery overview" })).toBeVisible({ timeout: 60_000 });
  const base = `/api/projects/${fixture.workspace}`;
  const read = async (path: string) => { const r = await page.request.get(path); expect(r.ok()).toBeTruthy(); return r.json(); };
  const before = await read(base+"/dashboard");
  expect(before.members).toHaveLength(6);
  const risks = await read(base+"/risks");
  expect(new Set(risks.filter((r: { active: boolean })=>r.active).map((r: { evidence: {kind:string} })=>r.evidence.kind))).toEqual(new Set(["ci_failure","dependency","review_delay","capacity"]));
  await page.screenshot({path:`evidence/supabase-overview-${info.project.name}.png`,fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  for (const [url,heading] of [["/tasks","Task board"],["/capacity","Team capacity"],["/audit","Audit log"],["/settings","Project settings"]]) {
    await page.goto(url); await expect(page.getByRole("heading",{name:heading,exact:true})).toBeVisible();
    await page.reload(); await expect(page.getByRole("heading",{name:heading,exact:true})).toBeVisible();
  }
  const origin = new URL(page.url()).origin;
  await page.goto('/tasks');
  await page.getByRole('button',{name:'Create task',exact:true}).click();
  const taskKey = 'QA-'+Date.now();
  await page.getByLabel('Task key',{exact:true}).fill(taskKey);
  await page.getByLabel('Title',{exact:true}).fill('Browser management check');
  await page.getByRole('dialog').getByRole('button',{name:'Create task',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button').filter({has:page.getByText(taskKey,{exact:true})}).click();
  await page.getByRole('button',{name:'Edit task details',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('Verified management check');
  await page.getByRole('button',{name:'Save details',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button').filter({has:page.getByText(taskKey,{exact:true})}).click();
  await page.getByRole('button',{name:'Edit task details',exact:true}).click();
  await page.getByRole('button',{name:'Archive task',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText(taskKey,{exact:true})).toHaveCount(0);
  const risk = risks.find((r: { evidence: { kind: string } })=>r.evidence.kind==="ci_failure");
  const propose = async () => { const r=await page.request.post(`/api/risks/${risk.id}/analyze?mode=rules`,{headers:{Origin:origin}});expect(r.ok()).toBeTruthy();return r.json(); };
  const first = await propose();
  const rejected = await page.request.post(`/api/proposals/${first.id}/decision`,{headers:{Origin:origin,"Idempotency-Key":crypto.randomUUID()},data:{decision:"reject",base_plan_version:first.base_plan_version}});
  expect(rejected.ok()).toBeTruthy();
  expect((await read(base+"/dashboard")).tasks).toEqual(before.tasks);
  const second = await propose();
  await page.goto(`/decisions/${second.id}`);
  await page.reload();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.screenshot({path:`evidence/supabase-proposal-${info.project.name}.png`,fullPage:true});
  await page.getByRole("button",{name:"Approve & apply",exact:true}).click();
  await expect(page.getByText("Decision recorded. The current plan and audit log are up to date.")).toBeVisible();
  const after = await read(base+"/dashboard");expect(after.plan_version).toBe(second.base_plan_version+1);
  await page.reload();expect((await read(base+"/dashboard")).plan_version).toBe(after.plan_version);
  expect((await read(base+"/audit")).some((a:{kind:string})=>a.kind==="proposal.approved")).toBeTruthy();
  // A fresh human-authored change remains available even when recovery candidates converge.
  const task=after.tasks.find((t:{key:string})=>t.key==="CAT-107");
  const pending=await page.request.post(base+"/proposals",{headers:{Origin:origin},data:{title:"Viewer permission check",base_plan_version:after.plan_version,actions:[{task_id:task.id,field:"priority",before:task.priority,after:task.priority==="high"?"normal":"high"}]}});
  expect(pending.ok()).toBeTruthy();const p=await pending.json();
  await page.request.post("/api/auth/logout",{headers:{Origin:origin}});
  await page.goto("/overview");
  await page.getByLabel("Email address").fill("jordan@teamflow.demo");
  await page.getByLabel("Password",{exact:true}).fill(fixture.password);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Delivery overview"})).toBeVisible();
  const denied=await page.request.post(`/api/proposals/${p.id}/decision`,{headers:{Origin:origin,"Idempotency-Key":crypto.randomUUID()},data:{decision:"approve",base_plan_version:p.base_plan_version}});
  expect(denied.status()).toBe(403);
  expect((await read(base+"/dashboard")).plan_version).toBe(after.plan_version);
  expect(errors).toEqual([]);
});
