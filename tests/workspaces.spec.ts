import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const fixture=JSON.parse(readFileSync('.local/hosted-demo.json','utf8'));
test('create real workspace, persist tasks/settings, invite teammate and enforce access',async({page},info)=>{
 test.setTimeout(240_000);
 page.setDefaultTimeout(30_000);
 page.setDefaultNavigationTimeout(45_000);
 console.info('Workspace flow: opening deployment');
 if(process.env.TEAMFLOW_VERCEL_SHARE_FILE)await page.goto(JSON.parse(readFileSync(process.env.TEAMFLOW_VERCEL_SHARE_FILE,'utf8')).url);
 async function login(email:string){await page.goto('/overview');await page.getByLabel('Email address').fill(email);await page.getByLabel('Password',{exact:true}).fill(fixture.passwords?.[email] ?? fixture.password);await page.getByRole('button',{name:'Sign in',exact:true}).click();await expect(page.getByRole('heading',{name:'Delivery overview'})).toBeVisible({timeout:60000});}
 await login('asha@teamflow.demo');
 console.info('Workspace flow: authenticated');
 const origin=new URL(page.url()).origin;
 const workspaceName=`Workflow verification ${info.project.name}`;
 const projects=await (await page.request.get('/api/projects')).json();
 let workspace=projects.find((p:{name:string})=>p.name===workspaceName);
 if(!workspace){
  if(info.project.name==='mobile')await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.getByRole('button',{name:'Create or join workspace',exact:true}).first().click();
  await page.getByLabel('Workspace name',{exact:true}).fill(workspaceName);
  await page.getByRole('button',{name:'Create empty workspace'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  workspace=(await (await page.request.get('/api/projects')).json()).find((p:{name:string})=>p.name===workspaceName);
 }else await page.getByLabel('Project',{exact:true}).selectOption(workspace.id);
 await expect(page.getByLabel('Project',{exact:true})).toHaveValue(workspace.id);
 await expect(page.getByText('DEMO WORKSPACE',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Replay demo event'})).toHaveCount(0);
 await page.goto('/settings');
 console.info('Workspace flow: editing settings');
 await expect(page.getByLabel('Workspace name',{exact:true})).toHaveValue(workspaceName);
 await page.getByRole('textbox',{name:'Description',exact:true}).fill('Real editable workspace, verified through the browser.');
 await page.getByLabel('PR review alert after (hours)').fill('36');
 await page.getByRole('button',{name:'Save workspace settings',exact:true}).click();
 await expect(page.getByText('Workspace settings saved. Risk rules use these values immediately.')).toBeVisible();
 await page.reload();await expect(page.getByLabel('PR review alert after (hours)')).toHaveValue('36');
 await page.getByLabel('Teammate email').fill('jordan@teamflow.demo');
 await page.getByLabel('Invitation role').selectOption('viewer');
 await page.getByRole('button',{name:'Create invitation link'}).click();
 const linkField=page.getByRole('textbox',{name:'Private invitation link'});
 await expect(linkField).toBeVisible();const link=await linkField.inputValue();
 await page.goto('/tasks');await page.getByRole('button',{name:'Create task',exact:true}).click();
 const key=`REAL-${Date.now()}`;
 await page.getByLabel('Task key',{exact:true}).fill(key);await page.getByLabel('Title',{exact:true}).fill('Our real delivery task');
 await page.getByRole('dialog').getByRole('button',{name:'Create task',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.reload();await expect(page.getByText(key,{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:`evidence/real-workspace-${info.project.name}.png`,fullPage:true});
 await page.request.post('/api/auth/logout',{headers:{Origin:origin}});
 await login('jordan@teamflow.demo');
 await page.goto(link);await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Accept invitation',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByLabel('Project',{exact:true})).toHaveValue(workspace.id);
 await page.goto('/tasks');await expect(page.getByText(key,{exact:true})).toBeVisible();await expect(page.getByRole('button',{name:'Create task',exact:true})).toHaveCount(0);
 const denied=await page.request.put(`/api/projects/${workspace.id}/settings`,{headers:{Origin:origin},data:{name:workspaceName,description:'unauthorized',tracked_branch:'main',review_threshold_hours:24,base_plan_version:1}});expect(denied.status()).toBe(403);
});
