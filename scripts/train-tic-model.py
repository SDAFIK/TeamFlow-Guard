"""CPU-only synthetic deadline-risk experiment; never loads production data."""
import json
import math
import random
from pathlib import Path

FEATURES = ['ci_failures', 'blocked', 'review_hours', 'downstream_count', 'deadline_hours', 'capacity_gap']
SEED = 42

def sigmoid(z):
    return 1 / (1 + math.exp(-max(-40, min(40, z))))

def dataset():
    rng = random.Random(SEED)
    rows = []
    for project in range(60):
        shift = rng.uniform(-0.7, 0.7)
        for _ in range(100):
            ci = min(5, int(rng.expovariate(1.1)))
            blocked = int(rng.random() < 0.18)
            review = min(120, rng.expovariate(1/24))
            downstream = rng.randint(0, 8)
            deadline = rng.uniform(4, 120)
            gap = rng.uniform(0, 1) if rng.random() < 0.45 else 0
            x = [ci, blocked, review, downstream, deadline, gap]
            logit = -2.0 + .47*ci + 1.3*blocked + .017*review + .11*downstream - .014*deadline + 1.6*gap + shift
            rows.append((project, x, int(rng.random() < sigmoid(logit))))
    return rows

def metrics(y, probabilities, threshold=.5):
    pred = [int(p >= threshold) for p in probabilities]
    tp = sum(a == b == 1 for a,b in zip(y,pred))
    fp = sum(a == 0 and b == 1 for a,b in zip(y,pred))
    fn = sum(a == 1 and b == 0 for a,b in zip(y,pred))
    precision = tp / max(1,tp+fp)
    recall = tp / max(1,tp+fn)
    return {k:round(v,6) for k,v in {'accuracy':sum(a==b for a,b in zip(y,pred))/len(y), 'precision':precision,'recall':recall,'f1':2*precision*recall/max(1e-12,precision+recall),'brier':sum((a-p)**2 for a,p in zip(y,probabilities))/len(y)}.items()}

def train():
    rows = dataset()
    train_rows = [r for r in rows if r[0] < 36]
    validation_rows = [r for r in rows if 36 <= r[0] < 48]
    test_rows = [r for r in rows if r[0] >= 48]
    n = len(train_rows)
    mean = [sum(r[1][i] for r in train_rows)/n for i in range(len(FEATURES))]
    scale = [max(1e-9,math.sqrt(sum((r[1][i]-mean[i])**2 for r in train_rows)/n)) for i in range(len(FEATURES))]
    xs = [[(v-m)/s for v,m,s in zip(r[1],mean,scale)] for r in train_rows]
    ys = [r[2] for r in train_rows]
    weights = [0.0]*len(FEATURES)
    bias = 0.0
    for _ in range(250):
        grad = [0.0]*len(FEATURES)
        gb = 0.0
        for x,y in zip(xs,ys):
            err = sigmoid(bias + sum(a*b for a,b in zip(x,weights)))-y
            gb += err
            for i,v in enumerate(x): grad[i] += err*v
        bias -= .2*gb/n
        weights = [w-.2*(g/n+.001*w) for w,g in zip(weights,grad)]
    def predict(rows):
        return [sigmoid(bias+sum(w*(v-m)/s for w,v,m,s in zip(weights,r[1],mean,scale))) for r in rows]
    val_y = [r[2] for r in validation_rows]
    val_p = predict(validation_rows)
    threshold = max((i/100 for i in range(10,91)),key=lambda t: (metrics(val_y,val_p,t)["f1"], t))
    y = [r[2] for r in test_rows]
    probabilities = predict(test_rows)
    baseline = [sum(ys)/n]*len(y)
    return {'version':'tic-synthetic-logistic-v2','status':'experimental_synthetic_only','seed':SEED,'features':FEATURES,'mean':mean,'scale':scale,'weights':weights,'bias':bias,'train_rows':n,'test_rows':len(y),'train_projects':36,'validation_projects':12,'validation_rows':len(val_y),'test_projects':12,'threshold':threshold,'metrics':{'logistic_default':metrics(y,probabilities),'logistic_validation_threshold':metrics(y,probabilities,threshold),'prevalence_baseline':metrics(y,baseline)},'limitations':'Synthetic labels are generated by an assumed formula; metrics do not establish real-world accuracy. Not for production decisions.'}

if __name__ == '__main__':
    model = train()
    path = Path(__file__).resolve().parents[1] / 'web/domain/models/tic-risk-v1.json'
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(model,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(model['metrics'],indent=2))
